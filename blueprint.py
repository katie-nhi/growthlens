def _render_summary(result):
    st.subheader("Analysis Summary")
    summary = result["summary"]
    col1, col2, col3 = st.columns(3)

    with col1:
        st.markdown("**Schema readiness**")
        if summary["readiness_present"]:
            for item in summary["readiness_present"]:
                st.markdown("- Present: " + item)
        if summary["readiness_missing"]:
            st.caption("Not declared: " + ", ".join(summary["readiness_missing"]))

    with col2:
        st.markdown("**Top recommendations**")
        for item in summary["top"]:
            st.markdown("- " + item["title"])

    with col3:
        st.markdown("**Missing prerequisites**")
        if summary["missing"]:
            for item in summary["missing"]:
                st.markdown("- %s (needs: %s)" % (item["title"], ", ".join(item["missing"])))
        else:
            st.caption("None for your stated objective.")

    if result["timestamp"]["kind"] in ("unix_ms", "unix_s"):
        st.warning(
            "Timestamp unit detected: %s. All date formulas convert the column to a "
            "real Date/Time value first (see the Excel & PivotTable Guide)."
            % result["timestamp"]["kind"].replace("_", " "),
            icon="\u23f1\ufe0f",
        )


def _render_metrics(metrics):
    rows = [m for m in metrics if m]
    if not rows:
        return
    frame = pd.DataFrame([
        {
            "Metric": m["name"],
            "Definition": m["definition"],
            "Numerator": m["numerator"],
            "Denominator": m["denominator"],
            "Required columns": ", ".join(m["required_columns"]) or "-",
        }
        for m in rows
    ])
    st.markdown("**Metric definitions**")
    st.dataframe(frame, width="stretch", hide_index=True)


def _render_analysis_plan(result):
    if result["blocked"]:
        for blocked in result["blocked"]:
            st.warning(
                "You mentioned something that fits '{}', but the schema is missing "
                "these inputs: {}. Add them to enable it.".format(
                    blocked["title"], ", ".join(blocked["missing"])
                )
            )
    if not result["analyses"]:
        st.error(
            "No analyses could be recommended from this schema. Add at least an "
            "identifier, timestamp, dimension or measure column."
        )
        return

    for analysis in result["analyses"]:
        expanded = bool(analysis.get("primary"))
        tag = "primary" if analysis.get("primary") else "secondary"
        with st.expander(analysis["title"] + "  (%s)" % tag, expanded=expanded):
            st.write(analysis["why"])
            _render_metrics(analysis["metrics"])
            for note in analysis.get("notes", []):
                st.caption("\u26a0\ufe0f " + note)


def _render_excel_guide(result):
    st.caption(engine.TABLE_NOTE)
    for analysis in result["analyses"]:
        with st.expander(analysis["title"], expanded=bool(analysis.get("primary"))):
            if analysis.get("formulas"):
                st.markdown("**Excel 365 formulas**")
                for item in analysis["formulas"]:
                    st.markdown("- " + item["label"])
                    st.code(item["formula"], language="excel")
                    if item.get("note"):
                        st.caption(item["note"])
            if analysis.get("power_query"):
                st.markdown("**Power Query approach (for ordered / grouped logic)**")
                for i, step in enumerate(analysis["power_query"], start=1):
                    st.write(str(i) + ". " + step)
            pivot = analysis["pivot"]
            st.markdown("**PivotTable configuration**")
            frame = pd.DataFrame([
                {"Area": "Rows", "Field(s)": ", ".join(pivot["rows"]) or "-"},
                {"Area": "Columns", "Field(s)": ", ".join(pivot["columns"]) or "-"},
                {"Area": "Values", "Field(s)": ", ".join(pivot["values"]) or "-"},
                {"Area": "Filters", "Field(s)": ", ".join(pivot["filters"]) or "-"},
                {"Area": "Aggregation", "Field(s)": pivot["aggregation"]},
            ])
            st.dataframe(frame, width="stretch", hide_index=True)


def _funnel_schematic(stages):
    """Schematic funnel: named stages, NO values shown."""
    fig = go.Figure(go.Funnel(
        y=stages,
        x=list(range(len(stages), 0, -1)),
        text=[s + "  -  ?" for s in stages],
        textinfo="text",
        marker={"color": "rgba(120,150,200,0.40)"},
    ))
    fig.update_layout(
        title="Schematic funnel - stage layout only (no values)",
        showlegend=False,
        height=120 + 70 * len(stages),
    )
    fig.update_xaxes(visible=False)
    return fig


def _cohort_heatmap(granularity):
    """Blank cohort heatmap with relative W0-W8 (or M0-M8 / D0-D8) columns."""
    letter = {"weekly": "W", "monthly": "M", "daily": "D"}.get(granularity, "M")
    columns = ["%s%d" % (letter, i) for i in range(9)]
    rows = ["Cohort 1", "Cohort 2", "Cohort 3", "Cohort 4", "Cohort 5"]
    z = [[None for _ in columns] for _ in rows]
    fig = go.Figure(go.Heatmap(
        z=z, x=columns, y=rows,
        colorscale="Blues", showscale=False,
        xgap=2, ygap=2,
    ))
    fig.update_layout(
        title="Cohort retention heatmap - blank template (%s0-%s8)" % (letter, letter),
        height=320,
    )
    fig.update_yaxes(autorange="reversed")
    return fig


def _render_dashboard_preview(result):
    dashboard = result["dashboard"]
    st.caption("Placeholders only - no figures are invented.")

    kpis = dashboard["kpis"]
    if kpis:
        cols = st.columns(min(len(kpis), 4))
        for i, kpi in enumerate(kpis):
            with cols[i % len(cols)]:
                st.metric(kpi["label"], kpi["placeholder"])
                st.caption(kpi["definition"])

    chart_by_type = {}
    for chart in dashboard["charts"]:
        chart_by_type[chart["title"]] = chart

    if "Funnel steps" in chart_by_type:
        st.markdown("**Funnel - schematic stage layout**")
        st.plotly_chart(_funnel_schematic(result["funnel_stages"] or ["Stage 1", "Stage 2", "Stage 3"]), use_container_width=True)
        st.caption("Schematic only: stage names are shown, widths are illustrative, and no values are displayed.")

    if "Cohort retention matrix" in chart_by_type:
        st.markdown("**Cohort retention - blank heatmap**")
        st.plotly_chart(_cohort_heatmap(result["time_granularity"]), use_container_width=True)
        st.caption("Blank template. Recent cohorts have fewer observable periods (far-right cells stay blank, not zero).")

    other_charts = [
        c for c in dashboard["charts"]
        if c["title"] not in ("Funnel steps", "Cohort retention matrix")
    ]
    for chart in other_charts:
        with st.container(border=True):
            st.markdown("**" + chart["title"] + "**  (" + chart["chart_type"] + ")")
            st.write(chart["axis"])
            st.caption(chart["note"])


def _render_setup(result):
    left, right = st.columns(2)
    with left:
        st.subheader("Local execution instructions")
        for i, step in enumerate(result["instructions"], start=1):
            st.write(str(i) + ". " + step)
    with right:
        st.subheader("Validation checklist")
        for item in result["checklist"]:
            st.checkbox(item, key="chk_" + item)


def _build_markdown(result):
    lines = ["# GrowthLens Analysis Blueprint", ""]
    if result["dataset_name"]:
        lines += ["**Dataset:** " + result["dataset_name"], ""]
    lines += [
        "**Objective:** " + result["objective"],
        "**Row granularity:** " + result["granularity"],
        "**Time granularity:** " + result["time_granularity"],
        "**Source:** rule-based (no AI/LLM used)",
        "",
        "## Analysis Summary",
        "- Schema readiness (present): " + ", ".join(result["summary"]["readiness_present"]),
        "- Top recommendations: " + ", ".join(t["title"] for t in result["summary"]["top"]),
    ]
    if result["summary"]["missing"]:
        for m in result["summary"]["missing"]:
            lines.append("- Missing prerequisite: %s (needs %s)" % (m["title"], ", ".join(m["missing"])))
    lines.append("")
    for analysis in result["analyses"]:
        lines += ["## " + analysis["title"], analysis["why"], ""]
        for m in analysis["metrics"]:
            if m:
                lines.append(
                    "- Metric: {} | numerator: {} | denominator: {} | columns: {}".format(
                        m["name"], m["numerator"], m["denominator"],
                        ", ".join(m["required_columns"]),
                    )
                )
        lines.append("")
        for f in analysis["formulas"]:
            lines.append("```excel\n" + f["formula"] + "\n```")
        if analysis.get("power_query"):
            lines.append("Power Query: " + " ".join(analysis["power_query"]))
        lines += ["", "Pivot: Rows={} | Columns={} | Values={} | Agg={}".format(
            analysis["pivot"]["rows"], analysis["pivot"]["columns"],
            analysis["pivot"]["values"], analysis["pivot"]["aggregation"]), ""]
        for note in analysis.get("notes", []):
            lines.append("Note: " + note)
        lines.append("")
    return "\n".join(lines)


def _render_results(result):
    st.divider()
    st.caption("Source: transparent rule-based logic. This is not AI-generated.")
    _render_summary(result)

    tab_plan, tab_excel, tab_dash, tab_setup = st.tabs([
        "Analysis Plan",
        "Excel & PivotTable Guide",
        "Dashboard Preview",
        "Setup & Checklist",
    ])
    with tab_plan:
        _render_analysis_plan(result)
    with tab_excel:
        _render_excel_guide(result)
    with tab_dash:
        _render_dashboard_preview(result)
    with tab_setup:
        _render_setup(result)
        st.download_button(
            "Download blueprint (Markdown)",
            data=_build_markdown(result),
            file_name="growthlens_blueprint.md",
            mime="text/markdown",
        )


def render_blueprint():
    _ensure_state()
    dataset_name, objective, granularity, time_granularity, funnel_stages = _render_header_form()
    edited = _render_schema_editor()

    if st.button("Generate Blueprint", type="primary"):
        schema = _records_to_schema(edited)
        errors = engine.validate_inputs(objective, granularity, schema)
        if errors:
            for err in errors:
                st.error(err)
            st.session_state.bp_result = None
        else:
            st.session_state.bp_result = engine.generate_blueprint(
                columns=schema,
                objective=objective,
                granularity=granularity,
                dataset_name=dataset_name,
                time_granularity=time_granularity,
                funnel_stages=funnel_stages,
            )

    if st.session_state.bp_result:
        _render_results(st.session_state.bp_result)
    else:
        st.caption("Fill in the objective and row granularity, then generate.")
