def _render_header_form():
    st.header("Build an Analysis Blueprint")
    st.write(
        "No file upload needed. Describe your dataset's **columns** and your "
        "**objective**, and GrowthLens will recommend analyses, Excel formulas "
        "and a blank dashboard plan."
    )
    st.info(METADATA_PRIVACY_NOTE, icon="\u2139\ufe0f")
    if not is_llm_configured():
        st.caption(
            "Recommendations are generated by transparent, rule-based logic - "
            "not by AI. No LLM is configured."
        )
    else:
        st.caption(
            "An LLM appears configured, but this build still uses rule-based logic."
        )

    dataset_name = st.text_input(
        "Dataset name (optional)",
        placeholder="e.g. Web analytics events export",
    )
    objective = st.text_area(
        "Business analysis objective (required)",
        placeholder=(
            "e.g. Find where users drop off in the signup funnel and how weekly "
            "retention differs by acquisition channel."
        ),
    )

    col_a, col_b = st.columns(2)
    with col_a:
        granularity = st.text_input(
            "Row granularity - what does one row represent? (required)",
            placeholder="e.g. one row = one event by one visitor",
        )
    with col_b:
        time_granularity = st.selectbox(
            "Desired time granularity (for cohorts and trends)",
            options=engine.TIME_GRANULARITIES,
            index=0,
            help=(
                "Auto infers from your objective. Weekly retention produces "
                "relative Week 0, Week 1, ... steps."
            ),
        )

    funnel_stages = st.text_input(
        "Optional funnel stage labels (comma-separated)",
        placeholder="e.g. view, cart, purchase",
        help=(
            "The real event values for each funnel step, in order. Leave blank to "
            "use placeholders you replace later."
        ),
    )
    return dataset_name, objective, granularity, time_granularity, funnel_stages


def _render_schema_editor():
    st.subheader("Column schema")
    st.caption(
        "One row per column. Add or remove rows with the controls. Enter metadata "
        "only - never real customer values."
    )
    with st.expander("What do the roles mean?", expanded=False):
        for key in engine.ROLES:
            st.markdown("- **%s** - %s" % (key, engine.ROLE_LABELS[key]))

    controls = st.columns(2)
    if controls[0].button("Load example schema"):
        st.session_state.bp_columns = _example_dataframe()
        st.rerun()
    if controls[1].button("Clear columns"):
        st.session_state.bp_columns = st.session_state.bp_columns.iloc[0:0]
        st.rerun()

    edited = st.data_editor(
        st.session_state.bp_columns,
        num_rows="dynamic",
        width="stretch",
        key="bp_schema_editor",
        column_config={
            "name": st.column_config.TextColumn(
                "Column name",
                help="The header as it appears in your file, e.g. visitorid.",
            ),
            "data_type": st.column_config.SelectboxColumn(
                "Data type",
                options=engine.DATA_TYPES,
                help="What kind of value the column holds.",
            ),
            "unit": st.column_config.TextColumn(
                "Unit",
                help="The measurement unit, e.g. Unix ms, USD, count, none.",
            ),
            "role": st.column_config.SelectboxColumn(
                "Role",
                options=ROLE_OPTIONS,
                help="How the analysis should treat this column.",
            ),
            "meaning": st.column_config.TextColumn(
                "Business meaning / purpose",
                help="A short description, e.g. 'event name: view, cart, purchase'.",
            ),
        },
    )
    st.session_state.bp_columns = edited
    return edited


