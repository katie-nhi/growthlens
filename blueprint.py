"""GrowthLens - Analysis Blueprint mode.

An interactive, rule-based form that works WITHOUT uploading any data. The user
describes their schema (columns, types, units, roles, meaning) and business
objective; the app returns analyses, metric definitions, Excel 365 formulas,
PivotTable configurations and a blank dashboard layout.

No real customer records are ever requested. No API keys live in this file.
"""

from __future__ import annotations

import pandas as pd
import plotly.graph_objects as go
import streamlit as st

import blueprint_engine as engine
from llm import is_llm_configured

METADATA_PRIVACY_NOTE = (
    "Privacy: if this app is hosted publicly, the schema metadata and objectives "
    "you enter are processed by the app server (not stored by GrowthLens and not "
    "sent to any LLM or third-party API in this phase). Treat column names, "
    "meanings and objectives as potentially sensitive and do not enter anything "
    "you are not allowed to share. This is a rule-based tool, not a "
    "confidentiality guarantee."
)

# Friendly role labels for the dropdown (mapped back to engine keys on submit).
ROLE_OPTIONS = [engine.ROLE_LABELS[k] for k in engine.ROLES]
_ROLE_LABEL_TO_KEY = {label: key for key, label in engine.ROLE_LABELS.items()}


# ---------------------------------------------------------------------------
# Schema <-> editor-dataframe conversion (so dropdowns show friendly labels)
# ---------------------------------------------------------------------------

def _to_editor(df):
    df = df.copy()
    if "role" in df.columns:
        df["role"] = df["role"].apply(
            lambda r: engine.ROLE_LABELS.get(str(r).strip().lower(), r)
        )
    return df


def _example_dataframe():
    return _to_editor(pd.DataFrame(engine.EXAMPLE_SCHEMA))


def _cell(record, key, default=""):
    value = record.get(key, default)
    if value is None or (isinstance(value, float) and pd.isna(value)):
        return default
    return str(value).strip()


def _records_to_schema(df):
    records = []
    for record in df.to_dict("records"):
        role_raw = _cell(record, "role")
        role = _ROLE_LABEL_TO_KEY.get(role_raw, role_raw.lower() or "ignore")
        data_type = _cell(record, "data_type", "text").lower() or "text"
        records.append({
            "name": _cell(record, "name"),
            "data_type": data_type,
            "unit": _cell(record, "unit"),
            "role": role,
            "meaning": _cell(record, "meaning"),
        })
    return engine.normalize_schema(records)


def _ensure_state():
    if "bp_columns" not in st.session_state:
        st.session_state.bp_columns = _example_dataframe()
    if "bp_result" not in st.session_state:
        st.session_state.bp_result = None


